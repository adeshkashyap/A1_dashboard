export function computeDemoStats(
  leads: Lead[],
  properties: Property[],
  reps: SalesRep[],
  whatsappStatus: WhatsAppStatus
): DashboardStats {
  const today = new Date().toDateString();
  const leadsToday = leads.filter(
    (l) => new Date(l.createdAt).toDateString() === today
  ).length;
  const pipelineValue = leads
    .filter((l) => l.status !== "LOST" && l.status !== "CLOSED")
    .reduce((sum, l) => sum + l.budget, 0);
  const closed = leads.filter((l) => l.status === "CLOSED").length;
  const conversionRate =
    leads.length === 0 ? 0 : Math.round((closed / leads.length) * 100);
  const topRep = [...reps]
    .filter((r) => r.active)
    .sort((a, b) => (b.conversionRate || 0) - (a.conversionRate || 0))[0];

  return {
    leadsToday: leadsToday || 4,
    pipelineValue,
    activeGroups: leads.filter((l) => l.status === "VISIT").length,
    conversionRate: conversionRate || 28,
    propertiesLive: properties.filter((p) => p.available).length,
    topRep: topRep
      ? { name: topRep.name, conversionRate: topRep.conversionRate || 0 }
      : undefined,
    whatsappStatus,
  };
}

